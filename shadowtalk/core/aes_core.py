_RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]


def _xtime(a: int) -> int:
    """GF(2^8) 乘法 by x。"""
    return ((a << 1) ^ 0x1b) & 0xff if a & 0x80 else (a << 1) & 0xff


def _gmul(a: int, b: int) -> int:
    """GF(2^8) 通用乘法。"""
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        a = _xtime(a)
        b >>= 1
    return p


class AES128:
    """AES-128 块加密（ECB 单块，供 CTR 模式调用）。"""

    def __init__(self, key: bytes):
        assert len(key) == 16, "AES-128 需要 16 字节密钥"
        self._round_keys = self._key_expansion(key)

    @staticmethod
    def _key_expansion(key: bytes) -> list:
        """密钥扩展：16 字节 → 11 个 16 字节轮密钥（44 个字）。

        标准 AES-128 密钥扩展算法，以 4 字节字为单位操作。
        """
        # 初始 4 个字
        w = []
        for i in range(4):
            w.append(list(key[i * 4:(i + 1) * 4]))

        for i in range(4, 44):
            prev = w[i - 1][:]
            if i % 4 == 0:
                # RotWord
                prev = prev[1:] + prev[:1]
                # SubWord
                prev = [_SBOX[b] for b in prev]
                # XOR RCON
                prev[0] ^= _RCON[i // 4 - 1]
            # w[i] = w[i-4] ^ prev
            w.append([a ^ b for a, b in zip(w[i - 4], prev)])

        # 分组为 11 个轮密钥（每个 4 个字 = 16 字节）
        return [bytes(w[i] + w[i + 1] + w[i + 2] + w[i + 3]) for i in range(0, 44, 4)]

    def _add_round_key(self, state: bytearray, round_key: bytes) -> None:
        for i in range(16):
            state[i] ^= round_key[i]

    def _sub_bytes(self, state: bytearray) -> None:
        for i in range(16):
            state[i] = _SBOX[state[i]]

    def _inv_sub_bytes(self, state: bytearray) -> None:
        for i in range(16):
            state[i] = _INV_SBOX[state[i]]

    def _shift_rows(self, state: bytearray) -> None:
        # 第 1 行左移 1
        state[1], state[5], state[9], state[13] = state[5], state[9], state[13], state[1]
        # 第 2 行左移 2
        state[2], state[6], state[10], state[14] = state[10], state[14], state[2], state[6]
        # 第 3 行左移 3
        state[3], state[7], state[11], state[15] = state[15], state[3], state[7], state[11]

    def _inv_shift_rows(self, state: bytearray) -> None:
        # 第 1 行右移 1
        state[1], state[5], state[9], state[13] = state[13], state[1], state[5], state[9]
        # 第 2 行右移 2
        state[2], state[6], state[10], state[14] = state[10], state[14], state[2], state[6]
        # 第 3 行右移 3
        state[3], state[7], state[11], state[15] = state[7], state[11], state[15], state[3]

    def _mix_columns(self, state: bytearray) -> None:
        for i in range(0, 16, 4):
            a = state[i:i + 4]
            state[i] = _gmul(a[0], 2) ^ _gmul(a[1], 3) ^ a[2] ^ a[3]
            state[i + 1] = a[0] ^ _gmul(a[1], 2) ^ _gmul(a[2], 3) ^ a[3]
            state[i + 2] = a[0] ^ a[1] ^ _gmul(a[2], 2) ^ _gmul(a[3], 3)
            state[i + 3] = _gmul(a[0], 3) ^ a[1] ^ a[2] ^ _gmul(a[3], 2)

    def _inv_mix_columns(self, state: bytearray) -> None:
        for i in range(0, 16, 4):
            a = state[i:i + 4]
            state[i] = _gmul(a[0], 14) ^ _gmul(a[1], 11) ^ _gmul(a[2], 13) ^ _gmul(a[3], 9)
            state[i + 1] = _gmul(a[0], 9) ^ _gmul(a[1], 14) ^ _gmul(a[2], 11) ^ _gmul(a[3], 13)
            state[i + 2] = _gmul(a[0], 13) ^ _gmul(a[1], 9) ^ _gmul(a[2], 14) ^ _gmul(a[3], 11)
            state[i + 3] = _gmul(a[0], 11) ^ _gmul(a[1], 13) ^ _gmul(a[2], 9) ^ _gmul(a[3], 14)

    def encrypt_block(self, block: bytes) -> bytes:
        """加密单个 16 字节块。"""
        assert len(block) == 16
        state = bytearray(block)
        self._add_round_key(state, self._round_keys[0])
        for r in range(1, 10):
            self._sub_bytes(state)
            self._shift_rows(state)
            self._mix_columns(state)
            self._add_round_key(state, self._round_keys[r])
        self._sub_bytes(state)
        self._shift_rows(state)
        self._add_round_key(state, self._round_keys[10])
        return bytes(state)

    def decrypt_block(self, block: bytes) -> bytes:
        """解密单个 16 字节块。"""
        assert len(block) == 16
        state = bytearray(block)
        self._add_round_key(state, self._round_keys[10])
        for r in range(9, 0, -1):
            self._inv_shift_rows(state)
            self._inv_sub_bytes(state)
            self._add_round_key(state, self._round_keys[r])
            self._inv_mix_columns(state)
        self._inv_shift_rows(state)
        self._inv_sub_bytes(state)
        self._add_round_key(state, self._round_keys[0])
        return bytes(state)


def aes_ctr_encrypt(key: bytes, plaintext: bytes) -> tuple:
    """AES-128-CTR 加密。返回 (nonce, ciphertext)。

    计数器块 = nonce (8 字节) || counter (8 字节大端)，共 16 字节。
    nonce 随机生成，counter 从 0 递增。
    """
    nonce = os.urandom(8)
    aes = AES128(key)
    ciphertext = bytearray()
    counter = 0
    for i in range(0, len(plaintext), 16):
        block = plaintext[i:i + 16]
        counter_block = nonce + struct.pack(">Q", counter)
        keystream = aes.encrypt_block(counter_block)
        for j in range(len(block)):
            ciphertext.append(block[j] ^ keystream[j])
        counter += 1
    return nonce, bytes(ciphertext)


def aes_ctr_decrypt(key: bytes, nonce: bytes, ciphertext: bytes) -> bytes:
    """AES-128-CTR 解密。CTR 模式解密 = 加密（对称）。"""
    aes = AES128(key)
    plaintext = bytearray()
    counter = 0
    for i in range(0, len(ciphertext), 16):
        block = ciphertext[i:i + 16]
        counter_block = nonce + struct.pack(">Q", counter)
        keystream = aes.encrypt_block(counter_block)
        for j in range(len(block)):
            plaintext.append(block[j] ^ keystream[j])
        counter += 1
    return bytes(plaintext)


def hmac_sha256(key: bytes, data: bytes) -> bytes:
    """HMAC-SHA256。"""
    return hmac.new(key, data, hashlib.sha256).digest()


def verify_hmac(key: bytes, data: bytes, expected: bytes) -> bool:
    """恒定时间 HMAC 验证。"""
    return hmac.compare_digest(hmac_sha256(key, data), expected)


def derive_key(password: bytes, salt: bytes, iterations: int = 100000) -> bytes:
    """PBKDF2-HMAC-SHA256 密钥派生。"""
    return hashlib.pbkdf2_hmac("sha256", password, salt, iterations, dklen=32)
